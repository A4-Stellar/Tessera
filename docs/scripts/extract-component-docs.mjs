/**
 * Component documentation extractor (issue #197).
 *
 * Parses the props, types, defaults and JSDoc of every component registered in
 * `mdx-components.tsx` (the components MDX authors can use) with
 * react-docgen-typescript, and generates one MDX reference page per component
 * plus an index under `app/[lang]/docs/components/`.
 *
 * Exits with code 1 when any prop lacks a JSDoc description, so CI fails
 * before undocumented props ship. With `--check` nothing is written; it also
 * fails when the committed pages are stale.
 *
 * Usage:
 *   node scripts/extract-component-docs.mjs          # regenerate the pages
 *   node scripts/extract-component-docs.mjs --check  # CI: validate JSDoc + freshness
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { withCustomConfig } from "react-docgen-typescript";

const CHECK = process.argv.includes("--check");
const DOCS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY_FILE = join(DOCS_ROOT, "mdx-components.tsx");
const OUTPUT_DIR = join(DOCS_ROOT, "app", "[lang]", "docs", "components");
const ROUTE = "/docs/components";
const BANNER = "{/* Generated by scripts/extract-component-docs.mjs from component JSDoc. Do not edit by hand. */}";
const MAX_DEFAULT_LENGTH = 60;

/** Components imported from `@/components/*` into the global MDX map: name → absolute file path. */
function registeredComponents() {
  const source = ts.createSourceFile(REGISTRY_FILE, readFileSync(REGISTRY_FILE, "utf8"), ts.ScriptTarget.Latest, false, ts.ScriptKind.TSX);
  const components = new Map();
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue;
    const specifier = statement.moduleSpecifier.text;
    if (!specifier.startsWith("@/components/") || statement.importClause?.isTypeOnly) continue;
    const file = join(DOCS_ROOT, `${specifier.slice(2)}.tsx`);
    const clause = statement.importClause;
    if (clause?.name) components.set(clause.name.text, file);
    if (clause?.namedBindings && ts.isNamedImports(clause.namedBindings)) {
      for (const element of clause.namedBindings.elements) {
        if (!element.isTypeOnly) components.set(element.name.text, file);
      }
    }
  }
  return components;
}

function slugify(name) {
  return name
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
}

/** A JSX string-literal expression: MDX renders it verbatim, so `{`, `<` and `|` need no escaping. */
const literal = (text) => `{${JSON.stringify(text)}}`;

const CODE_SPAN = /(`[^`\n]+`)/g;
const BULLET = /^[-*]\s+/;

/** Inline Markdown that keeps `code` spans and renders everything else literally. */
function inline(text) {
  return text
    .split(CODE_SPAN)
    .filter(Boolean)
    .map((part) => (part.startsWith("`") ? part : literal(part)))
    .join("");
}

/** The same rendering for JSX children, where Markdown code spans are not parsed. */
function inlineJsx(text) {
  return text
    .split(CODE_SPAN)
    .filter(Boolean)
    .map((part) => (part.startsWith("`") ? `<code>${literal(part.slice(1, -1))}</code>` : literal(part)))
    .join("");
}

/** JSDoc prose → MDX: consecutive `- ` lines become a list, other lines join into paragraphs. */
function prose(description) {
  const blocks = [];
  let paragraph = [];
  let list = [];
  const flush = () => {
    if (paragraph.length > 0) blocks.push(inline(paragraph.join(" ")));
    if (list.length > 0) blocks.push(list.map((item) => `- ${inline(item)}`).join("\n"));
    paragraph = [];
    list = [];
  };
  for (const raw of description.trim().split("\n")) {
    const line = raw.trim();
    if (!line) flush();
    else if (BULLET.test(line)) {
      if (paragraph.length > 0) flush();
      list.push(line.replace(BULLET, ""));
    } else {
      if (list.length > 0) flush();
      paragraph.push(line);
    }
  }
  flush();
  return blocks.join("\n\n");
}

/** Summary sentence: text before any bullet list, cut at the first sentence end that is not an initialism like "U.S.". */
function firstSentence(description) {
  const lead = description.split(/\n\s*[-*]\s/)[0].replace(/\s+/g, " ").trim();
  return lead.match(/^.*?(?<!\b[A-Z]\.[A-Z])[.!?](?=\s+[A-Z(]|$)/)?.[0] ?? lead;
}

function formatType(type) {
  if (type.name === "enum" && Array.isArray(type.value)) return type.value.map((member) => member.value).join(" | ");
  return type.name;
}

/** The default value cell: inline code, or plain text when there is none or it is too long to show. */
function defaultCell(prop) {
  const value = prop.defaultValue?.value;
  if (value === undefined || value === null) return "—";
  const text = String(value);
  if (text.includes("\n") || text.length > MAX_DEFAULT_LENGTH) return "See source";
  const stringTyped = prop.type.name === "string" || formatType(prop.type).startsWith('"');
  return `<code>${literal(stringTyped && !/^["'`]/.test(text) ? JSON.stringify(text) : text)}</code>`;
}

function propsTable(props) {
  const rows = props.map(
    (prop) => `    <tr>
      <td><code>${literal(prop.name)}</code></td>
      <td><code>${literal(formatType(prop.type))}</code></td>
      <td>${prop.required ? "Yes" : "No"}</td>
      <td>${defaultCell(prop)}</td>
      <td>${inlineJsx(prop.description.replace(/\s+/g, " ").trim())}</td>
    </tr>`
  );
  return `<table>
  <thead>
    <tr>
      <th>Prop</th>
      <th>Type</th>
      <th>Required</th>
      <th>Default</th>
      <th>Description</th>
    </tr>
  </thead>
  <tbody>
${rows.join("\n")}
  </tbody>
</table>`;
}

function metadata(title, description, canonical) {
  return `export const metadata = {\n  title: ${JSON.stringify(title)},\n  description: ${JSON.stringify(description)},\n  canonical: ${JSON.stringify(canonical)},\n};`;
}

function componentPage(doc) {
  const props = Object.values(doc.props);
  const summary = doc.description ? firstSentence(doc.description) : `${doc.displayName} component reference.`;
  return `${metadata(doc.displayName, summary, `${ROUTE}/${slugify(doc.displayName)}`)}

${BANNER}

# ${doc.displayName}

${doc.description ? prose(doc.description) : ""}

Source: \`${relative(DOCS_ROOT, doc.filePath)}\` · available in every MDX page as \`<${doc.displayName} />\`.

## Props

${props.length > 0 ? propsTable(props) : "This component takes no props."}
`;
}

function indexPage(docs) {
  const items = docs.map(
    (doc) => `- [${doc.displayName}](${ROUTE}/${slugify(doc.displayName)})${doc.description ? ` — ${inline(firstSentence(doc.description))}` : ""}`
  );
  return `${metadata("Component Library", "Props reference for every component available in Tessera MDX pages.", ROUTE)}

${BANNER}

# Component Library

Every component below is registered in \`mdx-components.tsx\`, so it can be used in any
MDX page without an import. Each reference is generated from the component's
TypeScript props and JSDoc comments.

${items.join("\n")}
`;
}

/** Recursively lists generated `page.mdx` files currently on disk. */
function existingPages(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return existingPages(path);
    return entry.name === "page.mdx" ? [path] : [];
  });
}

function main() {
  const registry = registeredComponents();
  const files = [...new Set(registry.values())];
  const parser = withCustomConfig(join(DOCS_ROOT, "tsconfig.json"), {
    savePropValueAsString: true,
    shouldExtractLiteralValuesFromEnum: true,
    shouldRemoveUndefinedFromOptional: true,
    // Undocumented `children` must fail the check like any other prop.
    skipChildrenPropWithoutDoc: false,
    // Inherited DOM/React props are documented upstream, not here.
    propFilter: (prop) => {
      const declarations = prop.declarations ?? [];
      return declarations.length === 0 || declarations.some((declaration) => !declaration.fileName.includes("/node_modules/"));
    },
  });

  // Files can export helpers too; keep only the registered component exports.
  const docs = parser
    .parse(files)
    .filter((doc) => registry.get(doc.displayName) === resolve(DOCS_ROOT, doc.filePath))
    .sort((a, b) => a.displayName.localeCompare(b.displayName));

  const undocumented = docs.flatMap((doc) =>
    Object.values(doc.props)
      .filter((prop) => !prop.description.trim())
      .map((prop) => `  ${relative(DOCS_ROOT, doc.filePath)}: ${doc.displayName}.${prop.name}`)
  );
  if (undocumented.length > 0) {
    console.error(`✖ ${undocumented.length} component prop(s) are missing a JSDoc description:\n${undocumented.join("\n")}`);
    process.exit(1);
  }

  const expected = new Map([[join(OUTPUT_DIR, "page.mdx"), indexPage(docs)]]);
  for (const doc of docs) expected.set(join(OUTPUT_DIR, slugify(doc.displayName), "page.mdx"), componentPage(doc));

  const stale = existingPages(OUTPUT_DIR).filter((path) => !expected.has(path));
  const changed = [...expected].filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);

  if (CHECK) {
    const problems = [...stale.map((path) => `  stale: ${relative(DOCS_ROOT, path)}`), ...changed.map(([path]) => `  outdated: ${relative(DOCS_ROOT, path)}`)];
    if (problems.length > 0) {
      console.error(`✖ Component docs are out of date. Run \`npm run docs:components\`:\n${problems.join("\n")}`);
      process.exit(1);
    }
    console.log(`✓ Component docs are up to date (${docs.length} components).`);
    return;
  }

  for (const path of stale) rmSync(dirname(path), { recursive: true, force: true });
  for (const [path, content] of changed) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  console.log(`✓ Generated docs for ${docs.length} components (${changed.length} written, ${stale.length} removed).`);
}

main();
