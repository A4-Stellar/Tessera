#!/usr/bin/env node
/**
 * Machine-translation workflow for the MDX documentation (issue #242).
 *
 * Translates `app/[lang]/docs/<route>/page.mdx` into
 * `app/[lang]/docs/<route>/page.<locale>.mdx` with an LLM, leaving code
 * blocks, JSX, `{expressions}`, inline code, link targets and glossary terms
 * untouched (see scripts/lib/mdx-translation.cjs). Every translation must pass
 * a JSX/code/link/heading parity check against its source before it is
 * written. Translated routes are wired so `/<locale>/docs/<route>` serves the
 * translation: the English source moves to `page.en.mdx` and a generated
 * `page.tsx` picks the file for the requested `[lang]`, falling back to English.
 *
 * Usage:
 *   node scripts/translate-docs.mjs [--locales es,fr] [--routes getting-started,api/assets]
 *                                   [--provider anthropic|openai|pseudo] [--model <id>]
 *                                   [--force] [--dry-run] [--no-wire] [--include-generated]
 *   node scripts/translate-docs.mjs --check [--strict]
 *
 * Environment:
 *   TRANSLATE_PROVIDER   default provider (anthropic)
 *   TRANSLATE_MODEL      model id (anthropic: claude-sonnet-5-5, openai: gpt-4o)
 *   ANTHROPIC_API_KEY    for --provider anthropic
 *   OPENAI_API_KEY, OPENAI_BASE_URL   for --provider openai (any compatible endpoint)
 *
 * A translation is skipped when its provenance header records the current
 * source hash (use --force to redo it). Files without that header are treated
 * as hand-written and never overwritten unless --force is given.
 *
 * --check validates every existing translation without calling a provider:
 * parity errors fail the run; stale translations (source changed) are
 * reported, and fail it with --strict.
 */

import { existsSync, readFileSync, readdirSync, renameSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const core = require("./lib/mdx-translation.cjs");

const DOCS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROUTES_ROOT = join(DOCS_ROOT, "app", "[lang]", "docs");
const GLOSSARY_FILE = join(DOCS_ROOT, "scripts", "translation-glossary.json");
const DEFAULT_MODELS = { anthropic: "claude-sonnet-5-5", openai: "gpt-4o", pseudo: "pseudo" };
// Generated by extract-component-docs.mjs, which rewrites page.mdx; translate the components' JSDoc instead.
const GENERATED_ROUTES = ["components"];

function parseArgs(argv) {
  const args = { flags: new Set(), values: {} };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith("--")) continue;
    const [key, inline] = arg.slice(2).split("=", 2);
    if (inline !== undefined) args.values[key] = inline;
    else if (argv[i + 1] && !argv[i + 1].startsWith("--") && ["locales", "routes", "provider", "model"].includes(key)) {
      args.values[key] = argv[++i];
    } else args.flags.add(key);
  }
  return args;
}

/** Locales from lib/i18n.ts, so the script and the site agree. */
function siteLocales() {
  const source = readFileSync(join(DOCS_ROOT, "lib", "i18n.ts"), "utf8");
  const match = /LOCALES\s*=\s*\[([^\]]+)\]/.exec(source);
  return match ? [...match[1].matchAll(/"([a-z-]+)"/g)].map((m) => m[1]) : ["en"];
}

/** Route directories containing an English source (`page.mdx` or wired `page.en.mdx`). */
function discoverRoutes(includeGenerated) {
  const routes = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (!statSync(full).isDirectory()) continue;
      const route = relative(ROUTES_ROOT, full).split(sep).join("/");
      if (!includeGenerated && GENERATED_ROUTES.some((g) => route === g || route.startsWith(`${g}/`))) continue;
      const source = ["page.en.mdx", "page.mdx"].map((f) => join(full, f)).find(existsSync);
      if (source) routes.push({ route, dir: full, source });
      walk(full);
    }
  };
  walk(ROUTES_ROOT);
  return routes.sort((a, b) => a.route.localeCompare(b.route));
}

function loadGlossary() {
  if (!existsSync(GLOSSARY_FILE)) return [...core.DEFAULT_GLOSSARY];
  const extra = JSON.parse(readFileSync(GLOSSARY_FILE, "utf8"));
  return [...new Set([...core.DEFAULT_GLOSSARY, ...(extra.terms ?? [])])];
}

/** Moves the English source to page.en.mdx and (re)generates the locale-switch page.tsx. */
function wireRoute(entry, log) {
  const locales = readdirSync(entry.dir)
    .map((f) => /^page\.([a-z]{2}(?:-[A-Z]{2})?)\.mdx$/.exec(f)?.[1])
    .filter((l) => l && l !== "en");
  if (locales.length === 0) return;
  const pageTsx = join(entry.dir, "page.tsx");
  if (existsSync(pageTsx) && !readFileSync(pageTsx, "utf8").startsWith(core.GENERATED_PAGE_MARKER)) {
    log(`  ! ${entry.route}: page.tsx is hand-written; not wiring translations`);
    return;
  }
  const english = join(entry.dir, "page.en.mdx");
  if (!existsSync(english)) {
    renameSync(join(entry.dir, "page.mdx"), english);
    entry.source = english;
  }
  writeFileSync(pageTsx, core.renderLocalePage(locales));
}

async function translate(args) {
  const all = siteLocales();
  const locales = (args.values.locales?.split(",") ?? all).map((l) => l.trim()).filter((l) => l && l !== "en");
  const unknown = locales.filter((l) => !all.includes(l));
  if (unknown.length) throw new Error(`Unknown locale(s) ${unknown.join(", ")}; site locales are ${all.join(", ")}`);

  const providerName = args.values.provider ?? process.env.TRANSLATE_PROVIDER ?? "anthropic";
  const model = args.values.model ?? process.env.TRANSLATE_MODEL ?? DEFAULT_MODELS[providerName];
  const glossary = loadGlossary();
  const dryRun = args.flags.has("dry-run");
  const translateBatch = core.createProvider({
    name: providerName,
    model,
    glossary,
    apiKey: providerName === "anthropic" ? process.env.ANTHROPIC_API_KEY : process.env.OPENAI_API_KEY,
    baseUrl: providerName === "openai" ? process.env.OPENAI_BASE_URL : process.env.ANTHROPIC_BASE_URL,
  });

  const wanted = args.values.routes?.split(",").map((r) => r.trim().replace(/^\/+|\/+$/g, ""));
  const routes = discoverRoutes(args.flags.has("include-generated")).filter((r) => !wanted || wanted.includes(r.route));
  if (wanted) {
    const missing = wanted.filter((w) => !routes.some((r) => r.route === w));
    if (missing.length) throw new Error(`No MDX source for route(s): ${missing.join(", ")}`);
  }

  const stats = { written: 0, skipped: 0, failed: 0 };
  for (const entry of routes) {
    const source = readFileSync(entry.source, "utf8");
    const sha = core.sourceHash(source);
    for (const locale of locales) {
      const target = join(entry.dir, `page.${locale}.mdx`);
      if (existsSync(target) && !args.flags.has("force")) {
        const provenance = core.readProvenance(readFileSync(target, "utf8"));
        if (!provenance || provenance.sha === sha) {
          stats.skipped++;
          continue;
        }
      }
      process.stdout.write(`→ ${entry.route} [${locale}] … `);
      try {
        const translated = await core.translateDocument(source, { locale, translateBatch, glossary });
        const errors = core.validateParity(source, translated);
        if (errors.length) throw new Error(`parity check failed:\n    ${errors.join("\n    ")}`);
        if (!dryRun) {
          writeFileSync(target, core.withProvenance(translated, { source: relative(DOCS_ROOT, entry.source), sha, locale, provider: `${providerName}:${model}` }));
        }
        stats.written++;
        console.log(dryRun ? "ok (dry run)" : "written");
      } catch (error) {
        stats.failed++;
        console.log(`FAILED\n    ${error.message}`);
      }
    }
    if (!dryRun && !args.flags.has("no-wire")) wireRoute(entry, console.log);
  }
  console.log(`\nTranslated ${stats.written}, skipped ${stats.skipped} up-to-date or hand-written, failed ${stats.failed}.`);
  return stats.failed === 0 ? 0 : 1;
}

function check(args) {
  const strict = args.flags.has("strict");
  let failures = 0;
  let stale = 0;
  let checked = 0;
  for (const entry of discoverRoutes(true)) {
    const source = readFileSync(entry.source, "utf8");
    const sha = core.sourceHash(source);
    for (const file of readdirSync(entry.dir)) {
      const locale = /^page\.([a-z]{2}(?:-[A-Z]{2})?)\.mdx$/.exec(file)?.[1];
      if (!locale || locale === "en") continue;
      checked++;
      const text = readFileSync(join(entry.dir, file), "utf8");
      const errors = core.validateParity(source, core.stripProvenance(text));
      if (errors.length) {
        failures++;
        console.log(`✗ ${entry.route} [${locale}]\n    ${errors.join("\n    ")}`);
      }
      const provenance = core.readProvenance(text);
      if (provenance && provenance.sha !== sha) {
        stale++;
        console.log(`${strict ? "✗" : "!"} ${entry.route} [${locale}] is stale: the English source changed since it was translated`);
      }
    }
    const pageTsx = join(entry.dir, "page.tsx");
    if (existsSync(join(entry.dir, "page.en.mdx")) && !existsSync(pageTsx)) {
      failures++;
      console.log(`✗ ${entry.route}: page.en.mdx exists but no page.tsx serves it`);
    }
  }
  console.log(`Checked ${checked} translation(s): ${failures} with errors, ${stale} stale.`);
  return failures > 0 || (strict && stale > 0) ? 1 : 0;
}

const args = parseArgs(process.argv.slice(2));
const run = args.flags.has("check") ? Promise.resolve(check(args)) : translate(args);
run.then(
  (code) => process.exit(code),
  (error) => {
    console.error(error.message);
    process.exit(1);
  }
);
