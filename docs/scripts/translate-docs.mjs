#!/usr/bin/env node
/**
 * Quality-controlled machine-translation workflow for MDX documentation (issues #242 & #442).
 *
 * Translates `app/[lang]/docs/<route>/page.mdx` into
 * `app/[lang]/docs/<route>/page.<locale>.mdx` with an LLM (Gemini, Anthropic,
 * OpenAI, or offline pseudo-translator), leaving code blocks, `{/* i18n-freeze *\/}`
 * blocks, JSX, `{expressions}`, inline code, link targets, Stellar contract
 * addresses, and glossary terms untouched (see scripts/lib/mdx-translation.cjs).
 *
 * Segments are cached in `scripts/translation_memory.json` keyed by SHA-256
 * content hash. Every translation must pass structural parity, MDX linting,
 * glossary auto-validation, and cross-file terminology consistency checks.
 *
 * Usage:
 *   node scripts/translate-docs.mjs [--locales es,fr,zh,ja,ar] [--routes getting-started,api/assets]
 *                                   [--provider gemini|anthropic|openai|pseudo] [--model <id>]
 *                                   [--tm scripts/translation_memory.json]
 *                                   [--force] [--dry-run] [--no-wire] [--include-generated]
 *   node scripts/translate-docs.mjs --check [--strict] [--validate-glossary]
 *                                   [--report-markdown <path>] [--report-json <path>]
 */

import { existsSync, readFileSync, readdirSync, renameSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const core = require("./lib/mdx-translation.cjs");

const DOCS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROUTES_ROOT = join(DOCS_ROOT, "app", "[lang]", "docs");
const GLOSSARY_FILE = join(DOCS_ROOT, "scripts", "translation-glossary.json");
const DEFAULT_TM_FILE = join(DOCS_ROOT, "scripts", "translation_memory.json");
const DEFAULT_MODELS = {
  gemini: "gemini-2.0-flash",
  anthropic: "claude-sonnet-5-5",
  openai: "gpt-4o",
  pseudo: "pseudo",
};
// Generated by extract-component-docs.mjs, which rewrites page.mdx; translate the components' JSDoc instead.
const GENERATED_ROUTES = ["components"];
const VALUE_ARGS = new Set(["locales", "routes", "provider", "model", "tm", "report-markdown", "report-json"]);

function parseArgs(argv) {
  const args = { flags: new Set(), values: {} };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith("--")) continue;
    const [key, inline] = arg.slice(2).split("=", 2);
    if (inline !== undefined) args.values[key] = inline;
    else if (argv[i + 1] && !argv[i + 1].startsWith("--") && VALUE_ARGS.has(key)) {
      args.values[key] = argv[++i];
    } else args.flags.add(key);
  }
  return args;
}

/** Locales from lib/i18n.ts, so the script and the site agree. */
function siteLocales() {
  const source = readFileSync(join(DOCS_ROOT, "lib", "i18n.ts"), "utf8");
  const match = /LOCALES\s*=\s*\[([^\]]+)\]/.exec(source);
  return match ? [...match[1].matchAll(/"([a-z-]+)"/g)].map((m) => m[1]) : ["en"];
}

/** Route directories containing an English source (`page.mdx` or wired `page.en.mdx`). */
function discoverRoutes(includeGenerated) {
  const routes = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (!statSync(full).isDirectory()) continue;
      const route = relative(ROUTES_ROOT, full).split(sep).join("/");
      if (!includeGenerated && GENERATED_ROUTES.some((g) => route === g || route.startsWith(`${g}/`))) continue;
      const source = ["page.en.mdx", "page.mdx"].map((f) => join(full, f)).find(existsSync);
      if (source) routes.push({ route, dir: full, source });
      walk(full);
    }
  };
  walk(ROUTES_ROOT);
  return routes.sort((a, b) => a.route.localeCompare(b.route));
}

function loadGlossaryData() {
  if (!existsSync(GLOSSARY_FILE)) return { terms: [] };
  return JSON.parse(readFileSync(GLOSSARY_FILE, "utf8"));
}

function loadGlossary() {
  const extra = loadGlossaryData();
  return [...new Set([...core.DEFAULT_GLOSSARY, ...(extra.terms ?? [])])];
}

function resolveApiKey(providerName) {
  if (providerName === "gemini") return process.env.GEMINI_API_KEY;
  if (providerName === "anthropic") return process.env.ANTHROPIC_API_KEY;
  if (providerName === "openai") return process.env.OPENAI_API_KEY;
  return undefined;
}

function resolveBaseUrl(providerName) {
  if (providerName === "gemini") return process.env.GEMINI_BASE_URL;
  if (providerName === "openai") return process.env.OPENAI_BASE_URL;
  return process.env.ANTHROPIC_BASE_URL;
}

/** Moves the English source to page.en.mdx and (re)generates the locale-switch page.tsx. */
function wireRoute(entry, log) {
  const locales = readdirSync(entry.dir)
    .map((f) => /^page\.([a-z]{2}(?:-[A-Z]{2})?)\.mdx$/.exec(f)?.[1])
    .filter((l) => l && l !== "en");
  if (locales.length === 0) return;
  const pageTsx = join(entry.dir, "page.tsx");
  if (existsSync(pageTsx) && !readFileSync(pageTsx, "utf8").startsWith(core.GENERATED_PAGE_MARKER)) {
    log(`  ! ${entry.route}: page.tsx is hand-written; not wiring translations`);
    return;
  }
  const english = join(entry.dir, "page.en.mdx");
  if (!existsSync(english)) {
    renameSync(join(entry.dir, "page.mdx"), english);
    entry.source = english;
  }
  writeFileSync(pageTsx, core.renderLocalePage(locales));
}

async function translate(args) {
  const all = siteLocales();
  const locales = (args.values.locales?.split(",") ?? all).map((l) => l.trim()).filter((l) => l && l !== "en");
  const unknown = locales.filter((l) => !all.includes(l));
  if (unknown.length) throw new Error(`Unknown locale(s) ${unknown.join(", ")}; site locales are ${all.join(", ")}`);

  const providerName = args.values.provider ?? process.env.TRANSLATE_PROVIDER ?? "gemini";
  const model = args.values.model ?? process.env.TRANSLATE_MODEL ?? DEFAULT_MODELS[providerName];
  const glossary = loadGlossary();
  const dryRun = args.flags.has("dry-run");
  const tmPath = args.values.tm ? resolve(DOCS_ROOT, args.values.tm) : DEFAULT_TM_FILE;
  const translationMemory = core.loadTranslationMemory(tmPath);

  const translateBatch = core.createProvider({
    name: providerName,
    model,
    glossary,
    apiKey: resolveApiKey(providerName),
    baseUrl: resolveBaseUrl(providerName),
  });

  const wanted = args.values.routes?.split(",").map((r) => r.trim().replace(/^\/+|\/+$/g, ""));
  const routes = discoverRoutes(args.flags.has("include-generated")).filter((r) => !wanted || wanted.includes(r.route));
  if (wanted) {
    const missing = wanted.filter((w) => !routes.some((r) => r.route === w));
    if (missing.length) throw new Error(`No MDX source for route(s): ${missing.join(", ")}`);
  }

  const stats = { written: 0, skipped: 0, failed: 0 };
  for (const entry of routes) {
    const source = readFileSync(entry.source, "utf8");
    const sha = core.sourceHash(source);
    for (const locale of locales) {
      const target = join(entry.dir, `page.${locale}.mdx`);
      if (existsSync(target) && !args.flags.has("force")) {
        const provenance = core.readProvenance(readFileSync(target, "utf8"));
        if (!provenance || provenance.sha === sha) {
          stats.skipped++;
          continue;
        }
      }
      process.stdout.write(`→ ${entry.route} [${locale}] … `);
      try {
        const translated = await core.translateDocument(source, {
          locale,
          translateBatch,
          glossary,
          translationMemory,
        });
        const errors = core.validateParity(source, translated);
        if (errors.length) throw new Error(`parity check failed:\n    ${errors.join("\n    ")}`);
        const lint = core.lintTranslatedMdx(source, translated, { docsRoot: DOCS_ROOT });
        if (!lint.valid) throw new Error(`MDX lint failed:\n    ${lint.errors.join("\n    ")}`);
        if (!dryRun) {
          writeFileSync(
            target,
            core.withProvenance(translated, {
              source: relative(DOCS_ROOT, entry.source),
              sha,
              locale,
              provider: `${providerName}:${model}`,
            })
          );
        }
        stats.written++;
        console.log(dryRun ? "ok (dry run)" : "written");
      } catch (error) {
        stats.failed++;
        console.log(`FAILED\n    ${error.message}`);
      }
    }
    if (!dryRun && !args.flags.has("no-wire")) wireRoute(entry, console.log);
  }
  if (!dryRun && stats.written > 0) {
    core.saveTranslationMemory(tmPath, translationMemory);
  }
  console.log(`\nTranslated ${stats.written}, skipped ${stats.skipped} up-to-date or hand-written, failed ${stats.failed}.`);
  return stats.failed === 0 ? 0 : 1;
}

function check(args) {
  const strict = args.flags.has("strict");
  const glossaryData = loadGlossaryData();
  const glossary = loadGlossary();
  let failures = 0;
  let stale = 0;
  let checked = 0;
  const englishSources = [];
  const translatedRecords = [];

  for (const entry of discoverRoutes(true)) {
    const source = readFileSync(entry.source, "utf8");
    const sha = core.sourceHash(source);
    if (!GENERATED_ROUTES.some((g) => entry.route === g || entry.route.startsWith(`${g}/`))) {
      englishSources.push({ route: entry.route, source });
    }
    for (const file of readdirSync(entry.dir)) {
      const locale = /^page\.([a-z]{2}(?:-[A-Z]{2})?)\.mdx$/.exec(file)?.[1];
      if (!locale || locale === "en") continue;
      checked++;
      const text = readFileSync(join(entry.dir, file), "utf8");
      const stripped = core.stripProvenance(text);
      const parityErrors = core.validateParity(source, stripped);
      const lint = core.lintTranslatedMdx(source, stripped, { docsRoot: DOCS_ROOT });
      const combinedErrors = [...new Set([...parityErrors, ...lint.errors])];

      translatedRecords.push({
        route: entry.route,
        locale,
        source,
        translated: stripped,
        parityErrors,
        lintErrors: lint.errors,
      });

      if (combinedErrors.length) {
        failures++;
        console.log(`✗ ${entry.route} [${locale}]\n    ${combinedErrors.join("\n    ")}`);
      }
      const provenance = core.readProvenance(text);
      if (provenance && provenance.sha !== sha) {
        stale++;
        console.log(`${strict ? "✗" : "!"} ${entry.route} [${locale}] is stale: the English source changed since it was translated`);
      }
    }
    const pageTsx = join(entry.dir, "page.tsx");
    if (existsSync(join(entry.dir, "page.en.mdx")) && !existsSync(pageTsx)) {
      failures++;
      console.log(`✗ ${entry.route}: page.en.mdx exists but no page.tsx serves it`);
    }
  }

  // Validate glossary against English MDX sources and translated records
  const glossaryValidation = core.validateGlossary(glossaryData, [...englishSources, ...translatedRecords]);
  if (!glossaryValidation.valid) {
    failures += glossaryValidation.errors.length;
    for (const err of glossaryValidation.errors) {
      console.log(`✗ Glossary: ${err}`);
    }
  }

  // Cross-file terminology consistency check across translated records
  const consistencyIssues = core.checkTerminologyConsistency(translatedRecords);
  if (consistencyIssues.length > 0) {
    failures += consistencyIssues.length;
    for (const issue of consistencyIssues) {
      console.log(`✗ Consistency: ${issue.message}`);
    }
  }

  const report = core.generateQualityReport(translatedRecords, {
    glossary,
    consistencyIssues,
    glossaryValidation,
    docsRoot: DOCS_ROOT,
  });

  if (args.values["report-markdown"]) {
    writeFileSync(resolve(DOCS_ROOT, args.values["report-markdown"]), report.markdown, "utf8");
  }
  if (args.values["report-json"]) {
    writeFileSync(resolve(DOCS_ROOT, args.values["report-json"]), `${JSON.stringify(report, null, 2)}\n`, "utf8");
  }

  console.log(`Checked ${checked} translation(s): ${failures} with errors, ${stale} stale.`);
  return failures > 0 || (strict && stale > 0) ? 1 : 0;
}

const args = parseArgs(process.argv.slice(2));
const run = args.flags.has("check") || args.flags.has("validate-glossary") ? Promise.resolve(check(args)) : translate(args);
run.then(
  (code) => process.exit(code),
  (error) => {
    console.error(error.message);
    process.exit(1);
  }
);
